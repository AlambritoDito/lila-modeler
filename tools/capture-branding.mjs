/** Browser acceptance + review screenshots for branding; uses only disposable contexts. */
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = fileURLToPath(new URL('../', import.meta.url));
const site = path.join(root, '_site');
const output = path.join(root, 'output/branding/review');
await mkdir(output, { recursive: true });
const mime = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.ico': 'image/x-icon', '.json': 'application/json', '.woff2': 'font/woff2' };
const server = createServer(async (req, res) => {
  try {
    const url = new URL(req.url, 'http://localhost');
    if (!url.pathname.startsWith('/lila-modeler/')) throw Error('base');
    let rel = decodeURIComponent(url.pathname.slice('/lila-modeler/'.length));
    if (!rel || rel.endsWith('/')) rel += 'index.html';
    const file = path.resolve(site, rel);
    if (!file.startsWith(site + path.sep)) throw Error('path');
    res.setHeader('Content-Type', mime[path.extname(file)] || 'application/octet-stream');
    res.end(await readFile(file));
  } catch { res.statusCode = 404; res.end('Not found'); }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const browser = await chromium.launch({ headless: true, ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
const base = `http://127.0.0.1:${server.address().port}/lila-modeler/`;
const version = JSON.parse(await readFile(path.join(root, 'apps/web/package.json'), 'utf8')).version;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'es-MX' });
  const page = await context.newPage();
  const errors = [], missing = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) missing.push(r.url()); });
  await page.goto(base);
  await page.locator('.hero-brand img').evaluate(img => img.decode());
  await page.screenshot({ path: path.join(output, 'product-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: path.join(output, 'product-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 900 });
  let release;
  const gate = new Promise(resolve => { release = resolve; });
  await page.route('**/assets/main-*.js', async route => { await gate; await route.continue(); });
  await page.goto(base + 'app/', { waitUntil: 'domcontentloaded' });
  await page.locator('.startup-logo').evaluate(img => img.decode());
  await page.getByText('Preparando tu espacio de trabajo…').waitFor();
  assert.equal(await page.locator('.startup-version').textContent(), `v${version}`);
  assert.equal(await page.locator('#root').evaluate(root => root.inert), true);
  await page.screenshot({ path: path.join(output, 'startup-desktop.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.startup-indicator').evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.screenshot({ path: path.join(output, 'startup-mobile.png') });
  release();
  await page.locator('#startup').waitFor({ state: 'detached' });
  assert.equal(await page.locator('#root').evaluate(root => root.inert), false);
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.reload();
  await page.locator('#startup').waitFor({ state: 'detached' });
  await page.locator('.identidad .logo').evaluate(img => img.decode());
  await page.locator('.zoom button').nth(2).click();
  await page.screenshot({ path: path.join(output, 'editor-dark.png') });
  await page.unroute('**/assets/main-*.js');
  await page.evaluate(() => { localStorage.setItem('lila.tema', 'papel'); localStorage.setItem('lila.temas', '{broken'); });
  await page.reload();
  await page.locator('#startup').waitFor({ state: 'detached' });
  await page.locator('.zoom button').nth(2).click();
  await page.screenshot({ path: path.join(output, 'editor-light.png') });
  const imgs = await page.locator('img').evaluateAll(imgs => imgs.every(i => i.complete && i.naturalWidth > 0));
  assert.equal(imgs, true); assert.deepEqual(errors, []); assert.deepEqual(missing, []);
  const nativeIcon = (await readFile(path.join(root, 'apps/desktop/resources/icons/icon.png'))).toString('base64');
  const alpha = await page.evaluate(async data => {
    const img = new Image(); img.src = `data:image/png;base64,${data}`; await img.decode();
    const canvas = document.createElement('canvas'); canvas.width = canvas.height = 1024;
    const ctx = canvas.getContext('2d'); ctx.drawImage(img, 0, 0);
    return [ctx.getImageData(0, 0, 1, 1).data[3], ctx.getImageData(512, 512, 1, 1).data[3]];
  }, nativeIcon);
  assert.deepEqual(alpha, [0, 255]);
  await context.close();
  const failure = await browser.newContext({ locale: 'es-MX', viewport: { width: 1440, height: 900 } });
  const broken = await failure.newPage();
  await broken.route('**/assets/main-*.js', route => route.abort());
  await broken.goto(base + 'app/');
  await broken.locator('#startup[data-state="error"]').waitFor();
  assert.match(await broken.locator('#startup-status').textContent(), /no pudo/);
  await broken.screenshot({ path: path.join(output, 'startup-error.png') });
  await broken.unroute('**/assets/main-*.js');
  await broken.locator('#startup-reload').click();
  await broken.locator('#startup').waitFor({ state: 'detached' });
  await failure.close();
  console.log('PASS: product responsive, slow startup, version, locale, inert state, reduced motion, both themes, corrupt preferences, failed bundle and reload recovery. No 404 or runtime errors in normal load.');
  console.log('Screenshots:', output);
} finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
